def render():
    ids = " | ".join(f"'{code}'" for code, *_ in SHOWERS)
    out = [HEADER.format(first=FIRST_YEAR, last=LAST_YEAR), TYPES.format(ids=ids, first=FIRST_YEAR, last=LAST_YEAR)]
    for utc, code, name, lam, zhr in peaks():
        out.append(f"  {{ id: '{code}', name: '{name}', utc: '{utc}', lambdaSun: {lam!r}, zhr: {zhr} }},\n")
    out.append("];\n")
    return "".join(out)


def main(argv):
    target = pathlib.Path(__file__).resolve().parent.parent / "ts" / "peaks.ts"
    if argv not in ([], ["--check"]):
        sys.exit("usage: gen-peaks.py [--check]")
    fresh = render()
    if argv == ["--check"]:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current == fresh:
            print(f"gen-peaks: {target.name} matches a fresh generation")
            return 0
        sys.stdout.writelines(list(difflib.unified_diff(
            current.splitlines(True), fresh.splitlines(True), "ts/peaks.ts", "fresh", n=1))[:40])
        print("gen-peaks: ts/peaks.ts is NOT what the generator writes: run tools/gen-peaks.py", file=sys.stderr)
        return 1
    target.write_text(fresh, encoding="utf-8", newline="\n")
    print(f"gen-peaks: wrote {target.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
