def series(table, tau):
    """Sum a VSOP87 variable: the sum over k of tau**k times the sum of A cos(B + C tau)."""
    total = 0.0
    for k, terms in enumerate(table):
        s = 0.0
        for a, b, c in terms:
            s += a * math.cos(b + c * tau)
        total += s * tau ** k
    return total


def delta_t_seconds(unix_seconds):
    """TT - UT in seconds: Espenak and Meeus, valid for 2005 to 2050."""
    year = 1970 + unix_seconds / (365.2425 * 86400)
    if not 2005 <= year <= 2050:
        raise ValueError(f"Delta T polynomial is valid for 2005 to 2050, not {year:.1f}")
    t = year - 2000
    return 62.92 + 0.32217 * t + 0.005589 * t * t


def sun_longitude(unix_seconds):
    """Geocentric ecliptic longitude of the Sun in degrees [0, 360), equinox J2000.0."""
    jde = unix_seconds / 86400 + UNIX_EPOCH_JD + delta_t_seconds(unix_seconds) / 86400
    tau = (jde - J2000_JD) / 365250
    lon = series(VSOP87B_EARTH["L"], tau)  # Earth, heliocentric, radians
    radius = series(VSOP87B_EARTH["R"], tau)  # astronomical units
    lon += -0.09033 * ARCSEC  # FK5 correction (the latitude part does not touch longitude)
    sun = math.degrees(lon) + 180.0  # the Sun as seen from the Earth
    if APPLY_ABERRATION:
        sun -= 20.4898 / radius / 3600
    return sun % 360.0


def crossing(year, target):
    """Unix seconds at which the Sun's longitude passes `target` degrees during `year`."""
    start = datetime.datetime(year, 1, 1, tzinfo=datetime.timezone.utc).timestamp()
    end = datetime.datetime(year + 1, 1, 1, tzinfo=datetime.timezone.utc).timestamp()
    t = start + ((target - sun_longitude(start)) % 360.0) / SUN_RATE * 86400
    for _ in range(50):
        err = (target - sun_longitude(t) + 180.0) % 360.0 - 180.0
        step = err / SUN_RATE * 86400
        t += step
        if abs(step) < 1e-3:
            break
    else:
        raise RuntimeError(f"no convergence for {target} in {year}")
    if not start <= t < end:
        raise RuntimeError(f"{target} in {year} fell outside the year: {t}")
    return t


def iso_minute(unix_seconds):
    minutes = math.floor(unix_seconds / 60 + 0.5)
    moment = datetime.datetime.fromtimestamp(minutes * 60, datetime.timezone.utc)
    return moment.strftime("%Y-%m-%dT%H:%MZ")


def peaks():
    rows = []
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        for code, name, lam, zhr in SHOWERS:
            rows.append((iso_minute(crossing(year, lam)), code, name, lam, zhr))
    rows.sort()
    return rows


