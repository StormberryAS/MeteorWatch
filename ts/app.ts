/* MeteorWatch Logic
   Determination of the next major meteor shower peak and of the Moon's light at that moment,
   calculated in the browser. The person can pick a city by hand from the built-in catalogue; the
   countdown then skips the showers that cannot be seen from that city, and times show in the
   city's time zone.

   Classic scripts, not modules: index.html loads suncalc.js (which publishes window.SunCalc,
   typed in ts/suncalc.d.ts), then peaks.js (the generated table of peak instants, generated by
   tools/gen-peaks.py as ts/peaks.ts and compiled to peaks.js), then visibility.js (the city
   filter's rule, ts/visibility.ts) and then app.js, and all four share one global scope.
   cities.js (the shared Stormberry Labs city catalogue, typed in ts/cities.d.ts) is not in the
   page: this file adds it, from the same origin, the first time the person uses the city field.
   This file has no import or export, so tsc compiles it to a plain script at the same path
   (app.js).
*/

interface UpcomingPeak {
  peak: ShowerPeak;
  /** The peak instant, milliseconds since the Unix epoch. */
  time: number;
}

interface Visibility {
  moonPhaseText: string;
  visibilityScore: 'EXCELLENT' | 'GOOD' | 'POOR';
  visibilityClass: 'visibility-excellent' | 'visibility-good' | 'visibility-poor';
}

/** A city the person picked: the fields of the catalogue row that the page uses. */
interface PickedCity {
  name: string;
  country: string;
  /** Decimal degrees, north positive. */
  lat: number;
  /** Decimal degrees, east positive. */
  lon: number;
  /** IANA time zone identifier, as the catalogue gives it; the browser may not know it (see zoneFor). */
  tz: string;
}

/**
 * What the countdown card shows. `index` is the position in SCHEDULE.
 * countdown: the next visible peak. passed: a visible peak less than GRACE_MS ago.
 * end: the table has no peak left that could be shown. none: a city is set and none of the
 * showers of the next 366 days can be seen from it.
 */
type Card =
  | { kind: 'countdown'; entry: UpcomingPeak; index: number }
  | { kind: 'passed'; entry: UpcomingPeak; index: number }
  | { kind: 'end' }
  | { kind: 'none' };

/** How long a shower stays on the card, marked as passed, after its peak: 12 hours. */
const GRACE_MS = 12 * 3600 * 1000;
/** How far ahead the page looks for a peak that can be seen from the city: 366 days. */
const HORIZON_MS = 366 * 86400 * 1000;
/** The key of the stored city in localStorage. */
const CITY_STORAGE_KEY = 'meteorwatch.city';

/**
 * Where the radiant is high enough to give a good show, from its declination (IMO Working
 * List, Table 5). Not the observer's position: the page never asks the device for its location.
 * The city filter uses only a city that the person picks by hand.
 */
const REGION: Readonly<Record<ShowerId, string>> = {
  QUA: 'Northern Hemisphere',
  LYR: 'Both, better in the north',
  ETA: 'Both, better in the south',
  SDA: 'Both, better in the south',
  PER: 'Northern Hemisphere',
  ORI: 'Both hemispheres',
  LEO: 'Both, better in the north',
  GEM: 'Both, better in the north',
  URS: 'Northern Hemisphere'
};

/** Every peak of the table with its instant parsed once. */
const SCHEDULE: readonly UpcomingPeak[] = PEAKS.map((peak) => ({ peak, time: Date.parse(peak.utc) }));

/** The city filter. Only a pick, the stored record at start-up, or Clear changes `city`. */
const state: { city: PickedCity | null } = { city: null };

/** What the card shows, as a key (kind, index, city), undefined before the first tick. */
let shownKey: string | undefined;
let timer: number | undefined;

/** Minutes of dark radiant time per SCHEDULE index, for the current city only. */
const darkCache = new Map<number, number>();

/** The element with this id; the page always has it, so a miss is a broken page. */
function byId(id: string): HTMLElement {
  const el = document.getElementById(id);
  if (!el) throw new Error(`MeteorWatch: #${id} is missing from the page`);
  return el;
}

/** The first peak strictly after `now` (milliseconds), or null when the table has run out. */
function findNextPeak(now: number): UpcomingPeak | null {
  let next: UpcomingPeak | null = null;
  for (const entry of SCHEDULE) {
    if (entry.time > now && (next === null || entry.time < next.time)) next = entry;
  }
  return next;
}

/**
 * The name of the Moon's phase from SunCalc's phase value (0 new, 0.25 first quarter, 0.5 full,
 * 0.75 last quarter). The four named phases are the bands of 0.03 either side of 0, 0.25, 0.5 and
 * 0.75, edges included, so the names mirror exactly (phase p and 1 - p); the crescents and
 * gibbous phases fill the gaps between them.
 */
function moonPhaseName(phase: number): string {
  if (phase <= 0.03 || phase >= 0.97) return 'New Moon';
  if (phase < 0.22) return 'Waxing Crescent';
  if (phase <= 0.28) return 'First Quarter';
  if (phase < 0.47) return 'Waxing Gibbous';
  if (phase <= 0.53) return 'Full Moon';
  if (phase < 0.72) return 'Waning Gibbous';
  if (phase <= 0.78) return 'Last Quarter';
  return 'Waning Crescent';
}

/**
 * The rating for a Moon that is `illuminationPct` percent lit. It takes the whole percentage
 * the page shows, so the number and the rating cannot disagree: under 20 is excellent, 20 to 59
 * is good, 60 and over is poor.
 */
function rateMoon(illuminationPct: number): Pick<Visibility, 'visibilityScore' | 'visibilityClass'> {
  if (illuminationPct < 20) return { visibilityScore: 'EXCELLENT', visibilityClass: 'visibility-excellent' };
  if (illuminationPct < 60) return { visibilityScore: 'GOOD', visibilityClass: 'visibility-good' };
  return { visibilityScore: 'POOR', visibilityClass: 'visibility-poor' };
}

/** The Moon at `peakDate`, as seen from the centre of the Earth: no position is used. */
function calculateVisibility(peakDate: Date): Visibility {
  const moon = SunCalc.getMoonIllumination(peakDate);
  const illuminationPct = Math.round(moon.fraction * 100);
  return {
    moonPhaseText: `${moonPhaseName(moon.phase)} (${illuminationPct}% illuminated)`,
    ...rateMoon(illuminationPct)
  };
}

/**
 * The peak in the viewer's time zone, date and time, with the zone's name: for example
 * "Wed, 18 Nov 2026, 00:43 CET". `timeZone` and `locale` default to the viewer's own.
 */
function formatPeak(time: number, timeZone?: string, locale?: string): string {
  return new Intl.DateTimeFormat(locale, {
    weekday: 'short', year: 'numeric', month: 'short', day: 'numeric',
    hour: '2-digit', minute: '2-digit', timeZone, timeZoneName: 'short'
  }).format(time);
}

/** "dd:hh:mm:ss" for a span in milliseconds; the days grow to three digits when they need to. */
function formatCountdown(diff: number): string {
  const total = Math.max(0, Math.floor(diff / 1000));
  const parts = [
    Math.floor(total / 86400),
    Math.floor((total % 86400) / 3600),
    Math.floor((total % 3600) / 60),
    total % 60
  ];
  return parts.map((n) => String(n).padStart(2, '0')).join(':');
}

/** Milliseconds from `now` to the start of the next whole second (1 to 1000). */
function nextTickDelay(now: number): number {
  return 1000 - (now % 1000);
}

/** "3 h 20 min", "14 h" or "55 min": whole minutes, rounded down, no leading zero. */
function formatDuration(minutes: number): string {
  const total = Math.max(0, Math.floor(minutes));
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (h > 0 && m > 0) return `${h} h ${m} min`;
  if (h > 0) return `${h} h`;
  return `${m} min`;
}

/** "Bergen, Norway". */
function cityLabel(city: PickedCity): string {
  return `${city.name}, ${city.country}`;
}

/** Zones already tried: true when this browser knows the zone. */
const zoneKnownCache = new Map<string, boolean>();

/** Whether this browser knows the IANA zone; an old WebView may lack a recent catalogue name. */
function zoneKnown(tz: string): boolean {
  let known = zoneKnownCache.get(tz);
  if (known === undefined) {
    try {
      new Intl.DateTimeFormat('en-GB', { timeZone: tz }); // throws RangeError for an unknown zone
      known = true;
    } catch {
      known = false;
    }
    zoneKnownCache.set(tz, known);
  }
  return known;
}

/** The zone for the times on the card: the city's, or undefined (the viewer's own) without a city or when this browser does not know the city's zone. */
function zoneFor(city: PickedCity | null): string | undefined {
  return city !== null && zoneKnown(city.tz) ? city.tz : undefined;
}

/** The line under the title: the city, and in which zone the times are. */
function cityLine(city: PickedCity): string {
  return zoneKnown(city.tz)
    ? `For ${cityLabel(city)}. Times are in the city's time zone.`
    : `For ${cityLabel(city)}. Times are in your own time zone, because this browser does not know the city's zone.`;
}

/** A list of names for a sentence: "A", "A and B", "A, B and C". */
function joinNames(names: readonly string[]): string {
  if (names.length <= 1) return names.join('');
  return `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}`;
}

/** The minutes of dark radiant time around the peak at `index`, from the city; calculated once per city. */
function darkMinutes(index: number, city: PickedCity): number {
  let minutes = darkCache.get(index);
  if (minutes === undefined) {
    const entry = SCHEDULE[index] as UpcomingPeak;
    minutes = darkRadiantMinutes(entry.time, entry.peak.ra, entry.peak.dec, city.lat, city.lon);
    darkCache.set(index, minutes);
  }
  return minutes;
}

/** Which peaks the city sees: all of them without a city. */
function visibleFor(city: PickedCity | null): (index: number) => boolean {
  if (city === null) return () => true;
  return (index) => isVisibleMinutes(darkMinutes(index, city));
}

/**
 * The card for the moment `now` (milliseconds). `visible(index)` says whether the peak at that
 * position in SCHEDULE can be seen. A peak that is hidden never gets a card.
 * 1. passed: the latest peak with time <= now < time + GRACE_MS.
 * 2. countdown: the first peak after now, within HORIZON_MS.
 * 3. end: the table has no peak left after now, or it ends within HORIZON_MS of now.
 * 4. none: any other case.
 * SCHEDULE is sorted by instant (tests/peaks.test.ts checks the table).
 */
function pickCard(now: number, visible: (index: number) => boolean): Card {
  let passed = -1;
  for (let i = 0; i < SCHEDULE.length; i++) {
    const t = (SCHEDULE[i] as UpcomingPeak).time;
    if (t <= now && now < t + GRACE_MS && visible(i)) passed = i;
  }
  if (passed >= 0) return { kind: 'passed', entry: SCHEDULE[passed] as UpcomingPeak, index: passed };
  for (let i = 0; i < SCHEDULE.length; i++) {
    const t = (SCHEDULE[i] as UpcomingPeak).time;
    if (t > now && t <= now + HORIZON_MS && visible(i)) return { kind: 'countdown', entry: SCHEDULE[i] as UpcomingPeak, index: i };
  }
  const last = SCHEDULE[SCHEDULE.length - 1];
  if (last === undefined || last.time <= now || last.time < now + HORIZON_MS) return { kind: 'end' };
  return { kind: 'none' };
}

function setText(id: string, text: string): void {
  const el = byId(id);
  if (el.textContent !== text) el.textContent = text;
}

function setHidden(id: string, hidden: boolean): void {
  const el = byId(id);
  if (el.hidden !== hidden) el.hidden = hidden;
}

/** The fields that change with the shower, not with the clock. */
function showPeak(entry: UpcomingPeak, index: number, city: PickedCity | null): void {
  byId('shower-name').textContent = entry.peak.name;
  byId('shower-date').className = 'event-value';
  byId('shower-region').textContent = REGION[entry.peak.id];
  byId('shower-zhr').textContent = `ZHR ${entry.peak.zhr}`;

  // The Moon at the true peak instant, not at some fixed hour of the day.
  const vis = calculateVisibility(new Date(entry.time));
  byId('shower-moon').textContent = vis.moonPhaseText;
  const visEl = byId('shower-visibility');
  visEl.textContent = vis.visibilityScore;
  visEl.className = `event-value visibility-pill ${vis.visibilityClass}`;

  if (city !== null) {
    byId('card-city').textContent = cityLine(city);
    byId('shower-dark').textContent = formatDuration(darkMinutes(index, city));
  }
  setHidden('card-city', city === null);
  setHidden('row-dark', city === null);
}

/** The table has no peak left: say so instead of leaving the card empty or stale. */
function showTableEnd(): void {
  byId('shower-name').textContent = 'No peak data';
  byId('countdown-timer').textContent = '--:--:--:--';
  byId('countdown-timer').classList.remove('countdown-long');
  byId('shower-date').textContent = `This version only knows peaks up to the end of ${PEAKS_LAST_YEAR}. A newer version of MeteorWatch has a longer table.`;
  // The message is long: let it use the full width of the card, under the label.
  byId('shower-date').className = 'event-value event-message';
  byId('shower-region').textContent = 'n/a';
  byId('shower-zhr').textContent = 'n/a';
  byId('shower-moon').textContent = 'n/a';
  const visEl = byId('shower-visibility');
  visEl.textContent = 'n/a';
  visEl.className = 'event-value';
  setHidden('card-city', true);
  setHidden('row-dark', true);
}

/** A city is set and none of the nine showers can be seen from it in the next 12 months. */
function showNoneVisible(city: PickedCity): void {
  byId('shower-name').textContent = 'No shower visible';
  byId('countdown-timer').textContent = '--:--:--:--';
  byId('countdown-timer').classList.remove('countdown-long');
  byId('shower-date').textContent = `None of the nine showers can be seen from ${city.name} in the next 12 months. Clear the city to see all showers.`;
  byId('shower-date').className = 'event-value event-message';
  byId('shower-region').textContent = 'n/a';
  byId('shower-zhr').textContent = 'n/a';
  byId('shower-moon').textContent = 'n/a';
  const visEl = byId('shower-visibility');
  visEl.textContent = 'n/a';
  visEl.className = 'event-value';
  byId('card-city').textContent = cityLine(city);
  setHidden('card-city', false);
  setHidden('row-dark', true);
}

/** The key that says whether the static fields of the card must be written again. */
function cardKey(card: Card, city: PickedCity | null): string {
  const cityKey = city === null ? '' : `${city.name}|${city.country}|${city.lat}|${city.lon}`;
  const index = card.kind === 'countdown' || card.kind === 'passed' ? card.index : -1;
  return `${card.kind}:${index}:${cityKey}`;
}

/** The fields that change with the card, not with the clock. */
function showCard(card: Card, city: PickedCity | null): void {
  const passed = card.kind === 'passed';
  byId('countdown-labels').hidden = passed;
  byId('countdown-timer').classList.toggle('countdown-passed', passed);
  setHidden('peak-status', !passed);
  setHidden('peak-next', true);
  setHidden('city-skipped', true);
  if (card.kind === 'countdown' || card.kind === 'passed') {
    showPeak(card.entry, card.index, city);
    if (passed) byId('countdown-timer').classList.remove('countdown-long');
  } else if (card.kind === 'end') {
    showTableEnd();
  } else if (city !== null) {
    showNoneVisible(city);
  }
}

/** The hidden showers whose peak lies after `now` and before the peak on the card. */
function skippedNames(now: number, until: number, city: PickedCity): string[] {
  const names: string[] = [];
  for (let i = 0; i < SCHEDULE.length; i++) {
    const entry = SCHEDULE[i] as UpcomingPeak;
    if (entry.time > now && entry.time < until && !isVisibleMinutes(darkMinutes(i, city))) names.push(entry.peak.name);
  }
  return names;
}

/** Draws the card and the clock. The next tick is armed in `finally`, so one error cannot stop the countdown. */
function updateUI(): void {
  try {
    const now = Date.now();
    const city = state.city;
    const card = pickCard(now, visibleFor(city));
    // The city's zone, or the viewer's own when there is no city or this browser does not know the zone.
    const zone = zoneFor(city);

    // The fields that depend on the card change only when the card does.
    const key = cardKey(card, city);
    if (key !== shownKey) {
      shownKey = key;
      showCard(card, city);
    }

    if (card.kind === 'countdown') {
      const countdown = formatCountdown(card.entry.time - now);
      setText('countdown-timer', countdown);
      // Three-digit days (the longest gap between peaks is about 109 days) take a smaller type size.
      byId('countdown-timer').classList.toggle('countdown-long', countdown.length > 11);
      // Formatted on every tick, so a change of the device's time zone (or of its daylight
      // saving offset) shows within a second.
      setText('shower-date', formatPeak(card.entry.time, zone));
      const skipped = city === null ? [] : skippedNames(now, card.entry.time, city);
      if (city !== null && skipped.length > 0) setText('city-skipped', `Not visible from ${city.name} before then: ${joinNames(skipped)}.`);
      setHidden('city-skipped', skipped.length === 0);
    } else if (card.kind === 'passed') {
      setText('countdown-timer', 'Peak passed');
      const minutes = Math.floor((now - card.entry.time) / 60000);
      setText('peak-status', minutes < 1 ? 'The peak was less than a minute ago.' : `The peak was ${formatDuration(minutes)} ago.`);
      setText('shower-date', formatPeak(card.entry.time, zone));
      // The next card that the countdown would show when the grace window ends.
      const after = pickCard(card.entry.time + GRACE_MS, visibleFor(city));
      if (after.kind === 'countdown') setText('peak-next', `Next: ${after.entry.peak.name}, ${formatPeak(after.entry.time, zone)}`);
      setHidden('peak-next', after.kind !== 'countdown');
    }
  } finally {
    // One timer, aligned to the clock's second; a pending one is replaced, not doubled.
    if (timer !== undefined) clearTimeout(timer);
    timer = window.setTimeout(updateUI, nextTickDelay(Date.now()));
  }
}

/* ================================================================
   CITY FILTER (the person picks a city by hand; nothing is sent anywhere)
   The search is MoonApp's (ts/app.ts of MoonApp, section 6), ported with its names so that
   tests/search.test.ts replays MoonApp's search vectors against it.
================================================================ */
interface CityElements {
  citySearch: HTMLInputElement;
  cityDropdown: HTMLUListElement;
  citySelected: HTMLElement;
  citySelectedTxt: HTMLElement;
  cityClearBtn: HTMLButtonElement;
  cityStatus: HTMLElement;
}

/** Filled by initCity() when the page has loaded. */
let els: CityElements;

let highlightedIndex = -1;
/** True while Clear moves the focus to the field: that focus must not start the download. */
let focusFromClear = false;
const LOADING_TEXT = 'Loading the city list.';
/** The one request for cities.js; a failed request is forgotten, so the next use tries again. */
let cataloguePromise: Promise<void> | null = null;

function setCityStatus(text: string): void {
  els.cityStatus.textContent = text;
}

/** Adds cities.js to the page, once, from the same origin; resolves when it has run. */
function loadCatalogue(): Promise<void> {
  if ('CITIES' in globalThis) return Promise.resolve();
  if (cataloguePromise !== null) return cataloguePromise;
  els.citySearch.setAttribute('aria-busy', 'true');
  const before = els.cityStatus.textContent ?? '';
  setCityStatus(LOADING_TEXT);
  const script = document.createElement('script');
  const loading = new Promise<void>((resolve, reject) => {
    script.addEventListener('load', () => resolve());
    script.addEventListener('error', () => reject(new Error('MeteorWatch: cities.js did not load')));
    script.src = './cities.js';
    document.head.appendChild(script);
  });
  cataloguePromise = loading;
  loading.then(
    () => {
      els.citySearch.removeAttribute('aria-busy');
      // Put back what the line said before the load (for example "Showing all showers."), unless
      // something else has written to it since.
      if (els.cityStatus.textContent === LOADING_TEXT) setCityStatus(before);
      // Text typed while the file loaded is not lost.
      onCityInput();
    },
    () => {
      cataloguePromise = null;
      script.remove();
      els.citySearch.removeAttribute('aria-busy');
      setCityStatus(state.city === null
        ? 'The city list did not load. All showers are shown.'
        : 'The city list did not load. The city you picked is still in use.');
    }
  );
  return loading;
}

/** Starts the load of cities.js when the field is used; the outcome is shown in the status line. */
function startCatalogueLoad(): void {
  loadCatalogue().catch(() => undefined);
}

function onCityInput(): void {
  // The catalogue is not there until the field has been used; nothing reads it before.
  if (!('CITIES' in globalThis)) return;
  const query = els.citySearch.value.trim().toLowerCase();
  if (query.length < 1) { closeDropdown(); return; }
  const qf = foldQuery(query);
  // Prefix matches first. With 25,000 cities a bare substring filter
  // buries the obvious answer: "erdal" returned Cloverdale, South
  // Riverdale and Terdal ahead of Erdal, and with only 8 rows shown the
  // city being typed could fall off the list entirely.
  const startsWith: City[] = [], contains: City[] = [];
  for (const c of CITIES) {
    // c.alt is the folded English exonym where GeoNames stores the local
    // name, so "gothenburg" finds Goteborg and "cologne" finds Koeln.
    if (c.fold.startsWith(qf) || c.alt.startsWith(qf)) startsWith.push(c);
    else if (c.fold.includes(qf) || c.alt.includes(qf) || c.cfold.includes(qf)) contains.push(c);
  }
  const matches = startsWith.concat(contains).slice(0, 8);
  if (!matches.length) { closeDropdown(); return; }
  renderDropdown(matches);
}

function renderDropdown(cities: City[]): void {
  els.cityDropdown.innerHTML = '';
  highlightedIndex = -1;
  els.citySearch.removeAttribute('aria-activedescendant');
  cities.forEach((city, idx) => {
    const li = document.createElement('li');
    li.setAttribute('role', 'option');
    li.setAttribute('id', 'city-option-' + idx);
    li.setAttribute('aria-selected', 'false');
    li.dataset.idx = String(idx);
    li.innerHTML = '<span class="city-name">' + escapeHtml(city.name) + '</span>'
                 + '<span class="city-country">' + escapeHtml(city.country) + '</span>';
    li._city = city;
    els.cityDropdown.appendChild(li);
  });
  els.cityDropdown.hidden = false;
  els.citySearch.setAttribute('aria-expanded', 'true');
}

function onCityKeydown(e: KeyboardEvent): void {
  if (els.cityDropdown.hidden) return;
  const items = els.cityDropdown.querySelectorAll('li');
  if (!items.length) return;
  if (e.key === 'ArrowDown') {
    e.preventDefault();
    highlightedIndex = Math.min(highlightedIndex + 1, items.length - 1);
    updateHighlight(items);
  } else if (e.key === 'ArrowUp') {
    e.preventDefault();
    highlightedIndex = Math.max(highlightedIndex - 1, 0);
    updateHighlight(items);
  } else if (e.key === 'Enter') {
    e.preventDefault();
    /* Every row was built by renderDropdown, which always sets _city, and highlightedIndex is
       either -1 or a row index (the two arrow keys clamp it), so the row exists. */
    if (highlightedIndex >= 0) selectCity((items[highlightedIndex] as HTMLLIElement)._city as City);
  } else if (e.key === 'Escape') {
    closeDropdown();
  }
}

function updateHighlight(items: NodeListOf<HTMLLIElement>): void {
  items.forEach((li, i) => {
    const on = i === highlightedIndex;
    li.classList.toggle('highlighted', on);
    li.setAttribute('aria-selected', String(on));
    if (on) {
      els.citySearch.setAttribute('aria-activedescendant', li.id);
      if (typeof li.scrollIntoView === 'function') li.scrollIntoView({ block: 'nearest' });
    }
  });
}

function onDropdownClick(e: MouseEvent): void {
  const li = (e.target as Element).closest('li');
  if (li && li._city) selectCity(li._city);
}

function selectCity(city: City): void {
  els.citySearch.value = '';
  closeDropdown();
  applyCity({ name: city.name, country: city.country, lat: city.lat, lon: city.lon, tz: city.tz }, true);
}

function clearCitySelection(): void {
  els.citySearch.value = '';
  closeDropdown();
  applyCity(null, true);
  // The focus goes back to the field for a keyboard user, but it must not start the download
  // (a return visit has not loaded the list) nor overwrite the status line of the clear.
  focusFromClear = true;
  try { els.citySearch.focus(); } finally { focusFromClear = false; }
}

function closeDropdown(): void {
  els.cityDropdown.hidden = true;
  els.cityDropdown.innerHTML = '';
  els.citySearch.setAttribute('aria-expanded', 'false');
  els.citySearch.removeAttribute('aria-activedescendant');
  highlightedIndex = -1;
}

/** Escapes HTML special chars to prevent XSS in city name display. */
function escapeHtml(str: string): string {
  return str.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
}

/** Shows the chosen city in the chip under the field, or hides the chip. */
function showCityChip(city: PickedCity | null): void {
  if (city !== null) els.citySelectedTxt.textContent = cityLabel(city);
  els.citySelected.hidden = city === null;
}

/**
 * Sets the city filter (null clears it), keeps it on this device when `save` is true, tells the
 * person through the status line, and redraws the card. The chosen city never leaves the device.
 */
function applyCity(city: PickedCity | null, save: boolean): void {
  state.city = city;
  darkCache.clear();
  let kept = true;
  if (save) kept = city === null ? forgetCity() : storeCity(city);
  showCityChip(city);
  if (city === null) setCityStatus('Showing all showers.');
  else setCityStatus(`Showing showers visible from ${cityLabel(city)}.`
    + (zoneKnown(city.tz) ? '' : ' This browser does not know the time zone of the city, so times show in your own time zone.')
    + (kept ? '' : ' This browser will not keep the city after you close the page.'));
  updateUI();
}

/* The stored city. Every access is in try and catch: a private window or a browser with site data
   switched off throws on the first touch of localStorage, and the page then works without it. */

/** Writes the record; false when this browser will not keep it. */
function storeCity(city: PickedCity): boolean {
  try {
    window.localStorage.setItem(CITY_STORAGE_KEY, JSON.stringify({ v: 1, name: city.name, country: city.country, lat: city.lat, lon: city.lon, tz: city.tz }));
    return true;
  } catch {
    return false;
  }
}

function forgetCity(): boolean {
  try {
    window.localStorage.removeItem(CITY_STORAGE_KEY);
    return true;
  } catch {
    return false;
  }
}

/** Whether a stored value is a record the page wrote: version, strings and ranges. A zone name that this browser does not know is kept (zoneFor then falls back to the viewer's zone). */
function parseStoredCity(raw: string): PickedCity | null {
  try {
    const rec: unknown = JSON.parse(raw);
    if (typeof rec !== 'object' || rec === null) return null;
    const r = rec as Record<string, unknown>;
    const text = (v: unknown): v is string => typeof v === 'string' && v.length >= 1 && v.length <= 200;
    const within = (v: unknown, limit: number): v is number => typeof v === 'number' && Number.isFinite(v) && v >= -limit && v <= limit;
    if (r.v !== 1 || !text(r.name) || !text(r.country) || !text(r.tz) || !within(r.lat, 90) || !within(r.lon, 180)) return null;
    return { name: r.name, country: r.country, lat: r.lat, lon: r.lon, tz: r.tz };
  } catch {
    return null;
  }
}

/** The stored city, or null. A record that fails the checks is removed. */
function readStoredCity(): PickedCity | null {
  let raw: string | null = null;
  try {
    raw = window.localStorage.getItem(CITY_STORAGE_KEY);
  } catch {
    return null;
  }
  if (raw === null) return null;
  const city = parseStoredCity(raw);
  if (city === null) forgetCity();
  return city;
}

/** Wires the chooser and restores the stored city; does not load cities.js and does not draw the card. */
function initCity(): void {
  els = {
    citySearch: byId('city-search') as HTMLInputElement,
    cityDropdown: byId('city-dropdown') as HTMLUListElement,
    citySelected: byId('city-selected'),
    citySelectedTxt: byId('city-selected-text'),
    cityClearBtn: byId('city-clear-btn') as HTMLButtonElement,
    cityStatus: byId('city-status'),
  };
  els.citySearch.addEventListener('input', () => { startCatalogueLoad(); onCityInput(); });
  els.citySearch.addEventListener('keydown', onCityKeydown);
  els.citySearch.addEventListener('focus', () => { if (!focusFromClear) startCatalogueLoad(); });
  els.citySearch.addEventListener('pointerdown', startCatalogueLoad);
  els.cityDropdown.addEventListener('click', onDropdownClick);
  els.cityClearBtn.addEventListener('click', clearCitySelection);
  /* Close dropdown when clicking outside the search widget */
  document.addEventListener('click', e => {
    if (!(els.citySearch.closest('.search-wrapper') as Element).contains(e.target as Node | null)) closeDropdown();
  });
  const stored = readStoredCity();
  if (stored !== null) {
    state.city = stored;
    showCityChip(stored);
  }
}

// Start the page
document.addEventListener('DOMContentLoaded', () => {
  initCity();
  updateUI();
});

