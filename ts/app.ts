/* MeteorWatch Logic
   Determination of the next major meteor shower peak and of the Moon's light at that moment,
   calculated in the browser.

   Classic scripts, not modules: index.html loads suncalc.js (which publishes window.SunCalc,
   typed in ts/suncalc.d.ts), then peaks.js (the generated table of peak instants, generated by
   tools/gen-peaks.py as ts/peaks.ts and compiled to peaks.js) and then app.js, and all three share one global scope.
   This file has no import or export, so tsc compiles it to a plain script at the same path
   (app.js).
*/

interface UpcomingPeak {
  peak: ShowerPeak;
  /** The peak instant, milliseconds since the Unix epoch. */
  time: number;
}

interface Visibility {
  moonPhaseText: string;
  visibilityScore: 'EXCELLENT' | 'GOOD' | 'POOR';
  visibilityClass: 'visibility-excellent' | 'visibility-good' | 'visibility-poor';
}

/**
 * Where the radiant is high enough to give a good show, from its declination (IMO Working
 * List, Table 5). Not the observer's position: the page asks for no location.
 */
const REGION: Readonly<Record<ShowerId, string>> = {
  QUA: 'Northern Hemisphere',
  LYR: 'Both, better in the north',
  ETA: 'Both, better in the south',
  SDA: 'Both, better in the south',
  PER: 'Northern Hemisphere',
  ORI: 'Both hemispheres',
  LEO: 'Both, better in the north',
  GEM: 'Both, better in the north',
  URS: 'Northern Hemisphere'
};

/** Every peak of the table with its instant parsed once. */
const SCHEDULE: readonly UpcomingPeak[] = PEAKS.map((peak) => ({ peak, time: Date.parse(peak.utc) }));

/** What the card shows: a peak, null for the end-of-table message, undefined before the first tick. */
let shown: UpcomingPeak | null | undefined;
let timer: number | undefined;

/** The element with this id; the page always has it, so a miss is a broken page. */
function byId(id: string): HTMLElement {
  const el = document.getElementById(id);
  if (!el) throw new Error(`MeteorWatch: #${id} is missing from the page`);
  return el;
}

/** The first peak strictly after `now` (milliseconds), or null when the table has run out. */
function findNextPeak(now: number): UpcomingPeak | null {
  let next: UpcomingPeak | null = null;
  for (const entry of SCHEDULE) {
    if (entry.time > now && (next === null || entry.time < next.time)) next = entry;
  }
  return next;
}

/**
 * The name of the Moon's phase from SunCalc's phase value (0 new, 0.25 first quarter, 0.5 full,
 * 0.75 last quarter). The four named phases are the bands of 0.03 either side of 0, 0.25, 0.5 and
 * 0.75, edges included, so the names mirror exactly (phase p and 1 - p); the crescents and
 * gibbous phases fill the gaps between them.
 */
function moonPhaseName(phase: number): string {
  if (phase <= 0.03 || phase >= 0.97) return 'New Moon';
  if (phase < 0.22) return 'Waxing Crescent';
  if (phase <= 0.28) return 'First Quarter';
  if (phase < 0.47) return 'Waxing Gibbous';
  if (phase <= 0.53) return 'Full Moon';
  if (phase < 0.72) return 'Waning Gibbous';
  if (phase <= 0.78) return 'Last Quarter';
  return 'Waning Crescent';
}

/**
 * The rating for a Moon that is `illuminationPct` percent lit. It takes the whole percentage
 * the page shows, so the number and the rating cannot disagree: under 20 is excellent, 20 to 59
 * is good, 60 and over is poor.
 */
function rateMoon(illuminationPct: number): Pick<Visibility, 'visibilityScore' | 'visibilityClass'> {
  if (illuminationPct < 20) return { visibilityScore: 'EXCELLENT', visibilityClass: 'visibility-excellent' };
  if (illuminationPct < 60) return { visibilityScore: 'GOOD', visibilityClass: 'visibility-good' };
  return { visibilityScore: 'POOR', visibilityClass: 'visibility-poor' };
}

/** The Moon at `peakDate`, as seen from the centre of the Earth: no position is used. */
function calculateVisibility(peakDate: Date): Visibility {
  const moon = SunCalc.getMoonIllumination(peakDate);
  const illuminationPct = Math.round(moon.fraction * 100);
  return {
    moonPhaseText: `${moonPhaseName(moon.phase)} (${illuminationPct}% illuminated)`,
    ...rateMoon(illuminationPct)
  };
}

/**
 * The peak in the viewer's time zone, date and time, with the zone's name: for example
 * "Wed, 18 Nov 2026, 00:43 CET". `timeZone` and `locale` default to the viewer's own.
 */
function formatPeak(time: number, timeZone?: string, locale?: string): string {
  return new Intl.DateTimeFormat(locale, {
    weekday: 'short', year: 'numeric', month: 'short', day: 'numeric',
    hour: '2-digit', minute: '2-digit', timeZone, timeZoneName: 'short'
  }).format(time);
}

/** "dd:hh:mm:ss" for a span in milliseconds; the days grow to three digits when they need to. */
function formatCountdown(diff: number): string {
  const total = Math.max(0, Math.floor(diff / 1000));
  const parts = [
    Math.floor(total / 86400),
    Math.floor((total % 86400) / 3600),
    Math.floor((total % 3600) / 60),
    total % 60
  ];
  return parts.map((n) => String(n).padStart(2, '0')).join(':');
}

/** Milliseconds from `now` to the start of the next whole second (1 to 1000). */
function nextTickDelay(now: number): number {
  return 1000 - (now % 1000);
}

/** The fields that change with the shower, not with the clock. */
function showPeak(next: UpcomingPeak): void {
  byId('shower-name').textContent = next.peak.name;
  byId('shower-date').className = 'event-value';
  byId('shower-region').textContent = REGION[next.peak.id];
  byId('shower-zhr').textContent = `ZHR ${next.peak.zhr}`;

  // The Moon at the true peak instant, not at some fixed hour of the day.
  const vis = calculateVisibility(new Date(next.time));
  byId('shower-moon').textContent = vis.moonPhaseText;
  const visEl = byId('shower-visibility');
  visEl.textContent = vis.visibilityScore;
  visEl.className = `event-value visibility-pill ${vis.visibilityClass}`;
}

/** The table has no peak left: say so instead of leaving the card empty or stale. */
function showTableEnd(): void {
  byId('shower-name').textContent = 'No peak data';
  byId('countdown-timer').textContent = '--:--:--:--';
  byId('countdown-timer').classList.remove('countdown-long');
  byId('shower-date').textContent = `This version only knows peaks up to the end of ${PEAKS_LAST_YEAR}. A newer version of MeteorWatch has a longer table.`;
  // The message is long: let it use the full width of the card, under the label.
  byId('shower-date').className = 'event-value event-message';
  byId('shower-region').textContent = 'n/a';
  byId('shower-zhr').textContent = 'n/a';
  byId('shower-moon').textContent = 'n/a';
  const visEl = byId('shower-visibility');
  visEl.textContent = 'n/a';
  visEl.className = 'event-value';
}

function setText(id: string, text: string): void {
  const el = byId(id);
  if (el.textContent !== text) el.textContent = text;
}

function updateUI(): void {
  const now = Date.now();
  const next = findNextPeak(now);

  // The fields that depend on the shower change only when the shower does (or when the table runs out).
  if (next !== shown) {
    shown = next;
    if (next === null) showTableEnd();
    else showPeak(next);
  }

  if (next !== null) {
    const countdown = formatCountdown(next.time - now);
    setText('countdown-timer', countdown);
    // Three-digit days (the longest gap between peaks is about 109 days) take a smaller type size.
    byId('countdown-timer').classList.toggle('countdown-long', countdown.length > 11);
    // Formatted on every tick, so a change of the device's time zone (or of its daylight
    // saving offset) shows within a second.
    setText('shower-date', formatPeak(next.time));
  }

  // One timer, aligned to the clock's second; a pending one is replaced, not doubled.
  if (timer !== undefined) clearTimeout(timer);
  timer = window.setTimeout(updateUI, nextTickDelay(Date.now()));
}

// Start the page
document.addEventListener('DOMContentLoaded', () => {
  updateUI();
});

// A hidden tab's timer may be held back for a minute or more: catch up the moment it is seen again.
document.addEventListener('visibilitychange', () => {
  if (!document.hidden) updateUI();
});
